import React, { useState } from "react";
import Json from "./components/JsonPane.jsx";

function CopyButton({ text, label = "Copy" }) {
  const [done, setDone] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text);
      setDone(true);
      setTimeout(() => setDone(false), 1500);
    } catch { /* no clipboard: the text is selectable */ }
  };
  return <button type="button" className="copy-btn" onClick={copy}>{done ? "Copied" : label}</button>;
}
export { CopyButton };

const POLICY_KIND = { hold: "hold for a human", scope: "scope gate", actsub: "act.sub gate" };
const VERDICT_LABEL = { approved: "APPROVED", rejected: "STEP-UP FAILED", held: "HELD", refused: "REFUSED", allowed: "ALLOWED" };

// The Cedar of every policy the door held during the run, as this lab's mock generates it (a reconstruction of the template's shape).
export function PolicyList({ policies }) {
  if (!policies || policies.length === 0) {
    return <p className="hint" data-testid="no-policies">No policy on the door: nothing can refuse or hold a call except sign-in.</p>;
  }
  return (
    <div className="policy-list" data-testid="policy-list">
      {policies.map((p) => (
        <article key={p.id} className="policy" data-testid={`policy-${p.id}`}>
          <header>
            <strong>{p.id}</strong>
            <span className={`chip state-${p.state.toLowerCase()}`}>{p.state}</span>
            <span className="hint">{POLICY_KIND[p.shape]} on {p.tool} ({p.action}): {p.value}</span>
            <CopyButton text={p.cedar} />
          </header>
          <pre className="cedar" data-testid={`cedar-${p.id}`}>{p.cedar}</pre>
        </article>
      ))}
      <p className="hint" data-testid="policy-provenance">
        This Cedar is generated by this lab from each case's shape, with example ids. Hold: the shape of the live HITL policy copy in the full
        demo app's notes (console text, not re-run here). Scope: the live scope policy copy and console template recorded there (console text,
        not re-run here). act.sub: only the contains(...) test inside forbid ... unless was read from the real tenant on 2026-11-16 (measured);
        the other lines are UNVERIFIED against the tenant.
      </p>
    </div>
  );
}

export default function RunResult({ result }) {
  if (!result) return null;
  return (
    <div className="run-result" data-testid="run-result">
      <h3>{result.label} <span className="chip">simulated run</span></h3>
      <PolicyList policies={result.policies} />
      <div className="call-list" data-testid="call-list">
        {result.calls.map((c) => (c.kind === "approval" ? (
          <div key={c.index} className={`call ${c.ok ? "approved" : "refused"}`} data-testid={`approval-${c.index}`}>
            <strong>Human approval</strong>{" "}
            <span className={`chip verdict-${c.ok ? "allowed" : "refused"}`} data-testid={`verdict-approval-${c.index}`}>{VERDICT_LABEL[c.verdict] || c.verdict.toUpperCase()}</span>{" "}
            <span className="hint">simulated{c.stepUpFailed || c.ok && (c.reason || "").includes("PingID step-up") ? " · PingID step-up (mock)" : ""}</span>
            <p className="run-reason" data-testid={`reason-approval-${c.index}`}>{c.reason}</p>
          </div>
        ) : (
          <div key={c.index} className={`call ${c.verdict}`} data-testid={`call-${c.index}`}>
            <strong>{c.tool}</strong> <span className="hint">{c.action}</span>{" "}
            <span className={`chip verdict-${c.verdict}`} data-testid={`verdict-${c.index}`}>{c.verdict.toUpperCase()}</span>{" "}
            <span className="hint">HTTP {c.http}{c.verdict === "held" ? " (simulated)" : ""}</span>
            <p className="run-reason" data-testid={`reason-${c.index}`}>{c.reason}</p>
          </div>
        )))}
      </div>
      {result.token ? (
        <details open>
          <summary>Mock token and its claims</summary>
          <p className="hint" data-testid="mock-token-label">
            <span className="chip basis-unmeasured">mock-issued</span> Issued by this lab's in-process PingFederate stand-in (HS256 fixture key);
            it signs nothing real. <CopyButton text={result.token.token} />
          </p>
          <Json value={result.token.token} label="Mock token" testId="mock-token" />
          <Json value={result.token.claims} label="Token claims (mock)" testId="token-claims" hot={["act", "sub", "scope", "mock"]} />
        </details>
      ) : (
        <p className="hint" data-testid="no-token">This run sends no token.</p>
      )}
      {result.traceparent && (
        <p className="hint" data-testid="run-traceparent">W3C traceparent of this run: <code>{result.traceparent}</code> (the page sent one; the server continued its trace)</p>
      )}
    </div>
  );
}
